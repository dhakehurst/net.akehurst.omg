package net.akehurst.omg.uml.v2_5_1.xmi

import net.akehurst.kotlinx.utils.Reference
import net.akehurst.omg.uml.v2_5_1.api.ReflectiveFeature
import net.akehurst.omg.uml.v2_5_1.api.ReflectiveFeatureKind
import net.akehurst.omg.uml.v2_5_1.api.UML.CommonStructure.Element
import net.akehurst.omg.uml.v2_5_1.api.UML_ModelFactory
import net.akehurst.omg.uml.v2_5_1.api.UML_ModelReflective
import net.akehurst.omg.uml.v2_5_1.api.UML_ModelReflectiveDefault
import net.akehurst.omg.uml.v2_5_1.ram.UML_ModelFactoryRam

/**
 * The UML 2.5.1 metamodel for the XMI reader, from the generated by-name API [UML_ModelReflective]:
 * objects are created and set by metaclass and feature names, as in the XMI. Inherited features are found too,
 * and a redefined feature may be given by the name of the feature it redefines.
 */
class UmlXmiMetamodel(
    val factory: UML_ModelFactory = UML_ModelFactoryRam("UML"),
) : XmiMetamodel, XmiIdentityProvider {

    val reflective: UML_ModelReflective = UML_ModelReflectiveDefault(factory)

    private val metaclasses = mutableMapOf<String, Metaclass?>()

    override fun metaclass(name: String): XmiMetaclass? = metaclasses.getOrPut(name) {
        reflective.isAbstract(name)?.let { Metaclass(name, it) }
    }

    override fun metaclassOf(obj: Any): XmiMetaclass? = reflective.metaclassOf(obj)?.let { metaclass(it) }

    override fun identityOf(obj: Any): Any? = (obj as? Element)?._identity

    inner class Metaclass(override val name: String, override val isAbstract: Boolean) : XmiMetaclass {
        override val superclassNames: List<String> by lazy { reflective.superclasses(name) }

        private val features = mutableMapOf<String, Feature?>()

        override fun feature(name: String): XmiMetaFeature? = features.getOrPut(name) {
            reflective.featureKind(this.name, name)?.let { Feature(it) }
        }

        fun isSubclassOf(superclassName: String): Boolean = name == superclassName || superclassName in superclassNames

        override fun construct(identity: Any): Any =
            reflective.construct(name, identity) ?: error("Could not create '$name'")

        override fun toString(): String = "uml:$name"
    }

    /** a feature of a metaclass, as the XMI reader uses it */
    inner class Feature(val feature: ReflectiveFeature) : XmiMetaFeature {
        override val name: String get() = feature.name
        override val isMany: Boolean get() = feature.isMany
        override val typeName: String get() = feature.typeName
        override val kind: XmiFeatureKind = when (feature.kind) {
            ReflectiveFeatureKind.VALUE -> XmiFeatureKind.DATA
            ReflectiveFeatureKind.CONTAINED -> XmiFeatureKind.COMPOSITE
            ReflectiveFeatureKind.REFERENCE -> XmiFeatureKind.REFERENCE
        }

        /** derived and read-only features are not set */
        override val isDerived: Boolean get() = feature.isSettable.not()

        private val isPrimitive = XmiDataConversion.isPrimitive(typeName)

        override fun convert(text: String): Any? = when {
            isPrimitive -> XmiDataConversion.convertPrimitive(typeName, text)
            else -> reflective.enumLiteral(typeName, text.trim())
        }

        override fun set(obj: Any, value: Any?) {
            val ok = when (kind) {
                XmiFeatureKind.DATA -> reflective.setValue(obj, name, value)
                XmiFeatureKind.COMPOSITE -> when {
                    isMany -> (value as Collection<*>).all { null != it && reflective.addContained(obj, name, it) }
                    null == value -> true
                    else -> reflective.addContained(obj, name, value)
                }

                XmiFeatureKind.REFERENCE -> when {
                    isMany -> (value as Collection<*>).all { addReference(obj, it) }
                    else -> setReference(obj, value)
                }
            }
            if (!ok) throw IllegalArgumentException("value not valid for '$name' of type '$typeName': $value")
        }

        private fun setReference(obj: Any, value: Any?): Boolean = when (value) {
            null -> true
            is Reference<*, *> -> value.reference?.let { reflective.setReference(obj, name, it, value.resolved) } ?: true
            else -> reflective.setReference(obj, name, identityOf(value) ?: value, value)
        }

        private fun addReference(obj: Any, value: Any?): Boolean = when (value) {
            null -> true
            is Reference<*, *> -> value.reference?.let { reflective.addReference(obj, name, it, value.resolved) } ?: true
            else -> reflective.addReference(obj, name, identityOf(value) ?: value, value)
        }

        override fun toString(): String = "$name: $typeName${if (isMany) "[*]" else ""} ($kind${if (isDerived) ", derived" else ""})"
    }
}
